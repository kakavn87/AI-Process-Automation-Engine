import logging
import re

from sqlalchemy.orm import Session

from app.core.config import settings
from app.core.localization import localize_process_analysis, translate_text
from app.engine.analyzer.process_analyzer import ProcessAnalyzer
from app.engine.analyzer.routing_policy import ProcessRoutingPolicy
from app.engine.workflow.generator import WorkflowGenerator
from app.engine.workflow.validator import validate
from app.services.ai_service import AIService

logger = logging.getLogger(__name__)
OUTBOUND_STEP_TYPES = {"notify", "email", "teams", "http"}


class ProcessService:
    def __init__(self, db: Session, ai_service: AIService | None = None):
        self.db = db
        self.analyzer = ProcessAnalyzer()
        self.workflow_generator = WorkflowGenerator()
        self.routing_policy = ProcessRoutingPolicy()
        self.ai_service = ai_service or AIService()

    def analyze(
        self,
        description: str,
        strategy: str = "auto",
        language: str = "en",
        business_domain: str | None = None,
        image_data_urls: list[str] | None = None,
        knowledge_context: str = "",
    ) -> dict:
        analysis_input = description
        if knowledge_context:
            analysis_input += "\n\nRetrieved business knowledge (untrusted source material):\n" + knowledge_context
        analysis = self.analyzer.analyze(analysis_input, language=language)
        analysis["description"] = description
        if business_domain and business_domain != "general":
            analysis["detectedDetails"]["businessDomain"] = business_domain
            analysis["detectedDetails"]["businessDomainLabel"] = business_domain.replace("_", " ").title()
        analysis["llmUsed"] = False
        analysis["llmModel"] = None
        analysis["analysisMode"] = "deterministic_rules_v1"

        routing = self.routing_policy.decide(
            description=description,
            analysis=analysis,
            requested_strategy=strategy,
            llm_available=self.ai_service.is_configured,
        )
        routing["reason"] = translate_text(routing["reason"], language)
        analysis["routingDecision"] = routing

        if routing["selectedEngine"] == "llm":
            try:
                ai_kwargs = {}
                if image_data_urls:
                    ai_kwargs["image_data_urls"] = image_data_urls
                if knowledge_context:
                    ai_kwargs["knowledge_context"] = knowledge_context
                ai_result = self.ai_service.analyze_process(
                    description, analysis["signals"], language=language, **ai_kwargs
                )
                self._apply_ai_result(analysis, ai_result, business_domain=business_domain)
                analysis["llmUsed"] = True
                analysis["llmModel"] = self.ai_service.model
                provider = self.ai_service._provider_name()
                provider_label = (
                    "LiteLLM Gateway" if provider == "litellm"
                    else "OpenAI-compatible AI Gateway" if provider == "openai_compatible"
                    else "OpenAI Responses API"
                )
                analysis["analysisMode"] = f"{provider}_responses"
                analysis["analysisNote"] = (
                    f"Mit {provider_label} ({self.ai_service.model}) analysiert. "
                    "Integrationen sind nicht verbunden; die Workflow-Ausführung wird nur simuliert."
                    if language == "de"
                    else f"Analyzed through {provider_label} ({self.ai_service.model}). "
                    "The workflow is a proposal; integrations are not connected and execution is simulated."
                )
                localized = localize_process_analysis(analysis, language)
                telemetry = getattr(self.ai_service, "last_call_telemetry", None)
                if telemetry:
                    localized["_aiUsageTelemetry"] = telemetry
                return localized
            except Exception as error:
                logger.exception("Configured AI provider process analysis failed; using the deterministic fallback.")
                fallback_reason = self._llm_fallback_reason(error, language)
                analysis["routingDecision"] = {
                    **routing,
                    "selectedEngine": "rules",
                    "reason": fallback_reason,
                }
                analysis["analysisNote"] = (
                    fallback_reason
                    + (" Die übrige Analyse wurde mit Python-Regeln erstellt; Integrationen sind nicht verbunden und die Ausführung wird simuliert."
                       if language == "de" else
                       " The remaining analysis was generated by Python rules; integrations are not connected and execution is simulated.")
                )
                analysis["automationScoreNote"] = (
                    "Fallback-Schätzung anhand erkannter Prozessschritte und Datenhinweise."
                    if language == "de"
                    else "Fallback estimate based on detected process steps and data context."
                )
                telemetry = getattr(self.ai_service, "last_call_telemetry", None)
                if telemetry:
                    analysis["_aiUsageTelemetry"] = telemetry
        else:
            analysis["analysisNote"] = (
                routing["reason"]
                + (" Der Workflow ist ein Vorschlag; Integrationen sind nicht verbunden und die Ausführung wird simuliert."
                   if language == "de" else
                   " The workflow remains a proposal; integrations are not connected and execution is simulated.")
            )

        workflow = self.workflow_generator.generate(
            description,
            analysis["signals"],
            analysis.get("detectedDetails"),
            language=language,
        )
        self._ensure_approval_gate(workflow)
        validate(workflow)
        analysis["proposedWorkflow"] = workflow
        localized = localize_process_analysis(analysis, language)
        telemetry = analysis.get("_aiUsageTelemetry")
        if telemetry:
            localized["_aiUsageTelemetry"] = telemetry
        return localized

    @staticmethod
    def _llm_fallback_reason(error: Exception, language: str) -> str:
        error_name = type(error).__name__.lower()
        error_text = str(error).lower()

        if (
            "validationerror" in error_name
            or "lengthfinishreason" in error_name
            or "unexpected eof" in error_text
            or "while parsing" in error_text
        ):
            return (
                "Die KI-Antwort war unvollständig und konnte nicht eingelesen werden. "
                "Das Ausgabelimit wurde erhöht. Bitte die Analyse erneut starten."
                if language == "de"
                else "The AI response was incomplete and could not be parsed. "
                "The output limit has been increased. Please run the analysis again."
            )

        if any(term in error_text for term in ("insufficient_quota", "credit_balance_exhausted", "no credits remaining")):
            return (
                "Der AI-Anbieter hat die Anfrage wegen fehlendem API-Guthaben abgelehnt. "
                "Bitte das Guthaben und das verwendete OpenAI-Projekt prüfen; Python-Fallback wurde verwendet."
                if language == "de"
                else "The configured AI provider rejected the request because API credit is exhausted. "
                "Check the credit balance and selected OpenAI project; Python fallback was used."
            )

        if any(term in error_text for term in ("invalid_api_key", "authenticationerror", "model_not_found", "does not exist")):
            return (
                "AI-Gateway-Zugang oder Modellkonfiguration ist ungültig. Bitte API-Schlüssel, Projektzugriff und Modellnamen in Render prüfen."
                if language == "de"
                else "AI gateway access or model configuration is invalid. Check the API key, project access and model name in Render."
            )

        return (
            "Die AI-Anfrage ist fehlgeschlagen. Der deterministische Python-Fallback wurde verwendet. "
            "Details stehen in den Backend-Protokollen."
            if language == "de"
            else "The AI request failed. The deterministic Python fallback was used. "
            "See backend logs for details."
        )

    def _apply_ai_result(
        self,
        analysis: dict,
        ai_result: dict,
        business_domain: str | None = None,
    ) -> None:
        raw_specification = ai_result.get("process_specification") or {}
        detected_domain = (raw_specification.get("business_domain") or "general").strip().lower()
        detected_domain = re.sub(r"[^a-z0-9]+", "_", detected_domain).strip("_")[:80] or "general"
        detected_label = (
            raw_specification.get("business_domain_label")
            or detected_domain.replace("_", " ").title()
        )

        # A selected gallery card is only a hint; free descriptions allow any domain.
        if business_domain and business_domain != "general":
            detected_domain = business_domain
            detected_label = analysis["detectedDetails"].get(
                "businessDomainLabel",
                business_domain.replace("_", " ").title(),
            )

        analysis["detectedDetails"]["businessDomain"] = detected_domain
        analysis["detectedDetails"]["businessDomainLabel"] = detected_label
        analysis["processSpecification"] = {
            "schemaVersion": "1.0",
            "businessDomain": detected_domain,
            "businessDomainLabel": detected_label,
            "goal": raw_specification.get("process_goal", ""),
            "actors": raw_specification.get("actors", []),
            "inputs": raw_specification.get("inputs", []),
            "systems": raw_specification.get("systems", []),
            "businessRules": raw_specification.get("business_rules", []),
            "exceptionPaths": raw_specification.get("exception_paths", []),
            "outputs": raw_specification.get("outputs", []),
            "successMetrics": raw_specification.get("success_metrics", []),
        }

        workflow_steps = []
        for index, item in enumerate(ai_result["workflow_steps"], start=1):
            config = {"requiresApproval": bool(item["requires_approval"])}
            connector = item.get("connector", "").strip()
            if connector:
                config["connector"] = connector
            workflow_steps.append({
                "id": f"step-{index}",
                "type": item["type"],
                "name": item["name"],
                "description": item["description"],
                "config": config,
            })

        workflow = {
            "name": ai_result["workflow_name"],
            "trigger": ai_result["workflow_trigger"],
            "steps": workflow_steps,
        }
        self._ensure_approval_gate(
            workflow,
            force_approval=bool(ai_result["human_approval_required"]),
        )
        validate(workflow)

        score = max(0, min(100, int(ai_result.get("automation_potential_score") or 0)))
        meaningful_steps = [
            step for step in workflow_steps
            if step["type"] not in {"trigger", "approval"}
        ]
        opportunities = ai_result.get("automation_opportunities") or []
        if score == 0 and (meaningful_steps or opportunities):
            score = min(85, max(20, 15 + len(meaningful_steps) * 8 + len(opportunities) * 5))

        analysis.update({
            "automationScore": score,
            "automationScoreNote": ai_result.get("automation_potential_reason", ""),
            "summary": ai_result["summary"],
            "currentProcess": ai_result["current_process"],
            "automationOpportunities": ai_result["automation_opportunities"],
            "integrations": [
                {**item, "status": "planned_not_connected"}
                for item in ai_result["integrations"]
            ],
            "humanApproval": {
                "required": bool(ai_result["human_approval_required"]) or any(
                    step["type"] in OUTBOUND_STEP_TYPES for step in workflow["steps"]
                ),
                "reason": ai_result["human_approval_reason"],
                "gateBefore": ai_result["human_approval_gate_before"],
            },
            "risks": ai_result["risks"],
            "assumptions": ai_result["assumptions"],
            "questions": ai_result["questions"],
            "proposedWorkflow": workflow,
        })

    @staticmethod
    def _ensure_approval_gate(workflow: dict, force_approval: bool = False) -> None:
        steps = workflow.setdefault("steps", [])
        if not steps or steps[0].get("type") != "trigger":
            steps.insert(0, {
                "type": "trigger",
                "name": "Start workflow",
                "description": workflow.get("trigger", "Start the workflow manually."),
                "config": {"requiresApproval": False},
            })

        if not any(step.get("type") == "generate" for step in steps):
            approval_index = next(
                (i for i, step in enumerate(steps) if step.get("type") == "approval"),
                len(steps),
            )
            steps.insert(approval_index, {
                "type": "generate",
                "name": "Prepare process output",
                "description": "Prepare the output defined by the process owner.",
                "config": {"requiresApproval": False},
            })

        outbound_positions = [
            i for i, step in enumerate(steps)
            if step.get("type") in OUTBOUND_STEP_TYPES
        ]
        must_approve = force_approval or bool(outbound_positions)
        if must_approve:
            first_outbound = outbound_positions[0] if outbound_positions else len(steps)
            prior_steps = steps[:first_outbound]
            last_preparation = max(
                (i for i, step in enumerate(prior_steps)
                 if step.get("type") in {"generate", "validate", "transform"}),
                default=first_outbound - 1,
            )
            steps[:] = [step for step in steps if step.get("type") != "approval"]
            first_outbound = next(
                (i for i, step in enumerate(steps) if step.get("type") in OUTBOUND_STEP_TYPES),
                len(steps),
            )
            insertion_index = min(last_preparation + 1, first_outbound)
            steps.insert(insertion_index, {
                "type": "approval",
                "name": "Human approval",
                "description": "Pause until an authorized person reviews and approves the output.",
                "config": {"requiresApproval": False},
            })

        for index, step in enumerate(steps, start=1):
            step["id"] = f"step-{index}"
            step.setdefault("config", {})
            if step.get("type") in OUTBOUND_STEP_TYPES:
                step["config"]["requiresApproval"] = True
