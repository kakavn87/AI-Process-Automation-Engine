import copy
import logging
import re

from sqlalchemy.orm import Session

from app.core.config import settings
from app.core.localization import localize_process_analysis, translate_text
from app.engine.analyzer.process_analyzer import ProcessAnalyzer
from app.engine.analyzer.routing_policy import ProcessRoutingPolicy
from app.engine.workflow.generator import WorkflowGenerator
from app.engine.workflow.validator import validate
from app.services.ai_service import AIService

logger = logging.getLogger(__name__)
OUTBOUND_STEP_TYPES = {"notify", "email", "teams", "http"}


class ProcessService:
    def __init__(self, db: Session, ai_service: AIService | None = None):
        self.db = db
        self.analyzer = ProcessAnalyzer()
        self.workflow_generator = WorkflowGenerator()
        self.routing_policy = ProcessRoutingPolicy()
        self.ai_service = ai_service or AIService()

    def analyze(
        self,
        description: str,
        strategy: str = "auto",
        language: str = "en",
        business_domain: str | None = None,
        image_data_urls: list[str] | None = None,
    ) -> dict:
        analysis = self.analyzer.analyze(description, language=language)
        if business_domain and business_domain != "general":
            analysis["detectedDetails"]["businessDomain"] = business_domain
            analysis["detectedDetails"]["businessDomainLabel"] = business_domain.replace("_", " ").title()
        analysis["llmUsed"] = False
        analysis["llmModel"] = None
        analysis["analysisMode"] = "deterministic_rules_v1"

        routing = self.routing_policy.decide(
            description=description,
            analysis=analysis,
            requested_strategy=strategy,
            llm_available=self.ai_service.is_configured,
        )
        routing["reason"] = translate_text(routing["reason"], language)
        analysis["routingDecision"] = routing

        if routing["selectedEngine"] == "llm":
            try:
                if image_data_urls:
                    ai_result = self.ai_service.analyze_process(
                        description, analysis["signals"], language=language,
                        image_data_urls=image_data_urls,
                    )
                else:
                    ai_result = self.ai_service.analyze_process(
                        description, analysis["signals"], language=language
                    )
                self._apply_ai_result(analysis, ai_result, business_domain=business_domain)
                analysis["llmUsed"] = True
                telemetry = getattr(self.ai_service, "last_call_telemetry", None)
                analysis["llmModel"] = (telemetry or {}).get("model") or self.ai_service.model
                analysis["analysisMode"] = "openai_responses"
                analysis["analysisNote"] = (
                    f"Mit der OpenAI Responses API ({self.ai_service.model}) analysiert. "
                    "Integrationen sind nicht verbunden; die Workflow-Ausführung wird nur simuliert."
                    if language == "de"
                    else f"Analyzed with OpenAI Responses API ({self.ai_service.model}). "
                    "The workflow is a proposal; integrations are not connected and execution is simulated."
                )
                localized = localize_process_analysis(analysis, language)
                telemetry = getattr(self.ai_service, "last_call_telemetry", None)
                if telemetry:
                    localized["_aiUsageTelemetry"] = telemetry
                return localized
            except Exception as error:
                logger.exception("OpenAI process analysis failed; using the deterministic fallback.")
                fallback_reason = self._llm_fallback_reason(error, language)
                analysis["routingDecision"] = {
                    **routing,
                    "selectedEngine": "rules",
                    "reason": fallback_reason,
                }
                analysis["analysisNote"] = (
                    fallback_reason
                    + (" Die übrige Analyse wurde mit Python-Regeln erstellt; Integrationen sind nicht verbunden und die Ausführung wird simuliert."
                       if language == "de" else
                       " The remaining analysis was generated by Python rules; integrations are not connected and execution is simulated.")
                )
                analysis["automationScoreNote"] = (
                    "Fallback-Schätzung anhand erkannter Prozessschritte und Datenhinweise."
                    if language == "de"
                    else "Fallback estimate based on detected process steps and data context."
                )
                telemetry = getattr(self.ai_service, "last_call_telemetry", None)
                if telemetry:
                    analysis["_aiUsageTelemetry"] = telemetry
        else:
            analysis["analysisNote"] = (
                routing["reason"]
                + (" Der Workflow ist ein Vorschlag; Integrationen sind nicht verbunden und die Ausführung wird simuliert."
                   if language == "de" else
                   " The workflow remains a proposal; integrations are not connected and execution is simulated.")
            )

        workflow = self.workflow_generator.generate(
            description,
            analysis["signals"],
            analysis.get("detectedDetails"),
            language=language,
        )
        self._ensure_approval_gate(workflow)
        validate(workflow)
        analysis["proposedWorkflow"] = workflow
        localized = localize_process_analysis(analysis, language)
        telemetry = analysis.get("_aiUsageTelemetry")
        if telemetry:
            localized["_aiUsageTelemetry"] = telemetry
        return localized


    def optimize_after_clarification(
        self,
        analysis: dict,
        description: str,
        questions: list[dict],
        answers: dict,
        strategy: str = "auto",
        language: str = "de",
    ) -> dict:
        """Run the second LLM pass after all required clarification answers are available."""
        optimized = copy.deepcopy(analysis)
        original_workflow = copy.deepcopy(optimized.get("proposedWorkflow") or {})
        optimized["originalWorkflow"] = original_workflow

        should_use_llm = (
            strategy != "rules"
            and bool(optimized.get("llmUsed"))
            and self.ai_service.is_configured
        )
        if not should_use_llm:
            if strategy == "rules":
                note = (
                    "Der Python-Regelmodus wurde gewählt. Die Antworten wurden deterministisch übernommen; "
                    "eine zusätzliche LLM-Optimierung wurde bewusst nicht aufgerufen."
                    if language == "de"
                    else "Python rules mode was selected. Answers were applied deterministically; no additional LLM optimization was called."
                )
                status = "rules_only"
            else:
                note = (
                    "Für die erste Analyse wurde kein LLM-Ergebnis verwendet. Die Antworten wurden mit Python geprüft; "
                    "für eine KI-Optimierung ist eine erfolgreiche LLM-Analyse mit aktivem API-Zugang erforderlich."
                    if language == "de"
                    else "The first analysis did not use an LLM result. Python validated the answers; AI optimization requires a successful first-stage LLM analysis and an active API connection."
                )
                status = "unavailable"
            optimized["optimization"] = {
                "status": status,
                "engine": "python",
                "summary": note,
                "designPrinciples": [],
                "recommendedChanges": [],
                "expectedBenefits": [],
                "model": None,
            }
            return optimized

        try:
            ai_result = self.ai_service.optimize_process(
                description=description,
                analysis=optimized,
                questions=questions,
                answers=answers,
                language=language,
            )
            self._apply_optimization_result(optimized, ai_result)
            telemetry = getattr(self.ai_service, "last_call_telemetry", None)
            if telemetry:
                optimized["_optimizationUsageTelemetry"] = telemetry
            return optimized
        except Exception as error:
            logger.exception("Second-stage AI process optimization failed; retaining the original workflow.")
            note = self._llm_fallback_reason(error, language)
            optimized["optimization"] = {
                "status": "fallback",
                "engine": "python",
                "summary": note,
                "designPrinciples": [],
                "recommendedChanges": [],
                "expectedBenefits": [],
                "model": getattr(self.ai_service, "model", None),
            }
            telemetry = getattr(self.ai_service, "last_call_telemetry", None)
            if telemetry:
                optimized["_optimizationUsageTelemetry"] = telemetry
            return optimized

    def _apply_optimization_result(self, analysis: dict, result: dict) -> None:
        """Apply and validate the LLM target design; calculate evidence-backed deltas in Python."""
        raw_specification = result.get("process_specification") or {}
        detected_details = analysis.setdefault("detectedDetails", {})
        domain = (raw_specification.get("business_domain") or detected_details.get("businessDomain") or "general")
        domain = re.sub(r"[^a-z0-9]+", "_", domain.strip().lower()).strip("_")[:80] or "general"
        domain_label = (
            raw_specification.get("business_domain_label")
            or detected_details.get("businessDomainLabel")
            or domain.replace("_", " ").title()
        )
        detected_details["businessDomain"] = domain
        detected_details["businessDomainLabel"] = domain_label

        analysis["processSpecification"] = {
            "schemaVersion": "1.0",
            "businessDomain": domain,
            "businessDomainLabel": domain_label,
            "goal": raw_specification.get("process_goal", ""),
            "actors": raw_specification.get("actors", []),
            "inputs": raw_specification.get("inputs", []),
            "systems": raw_specification.get("systems", []),
            "businessRules": raw_specification.get("business_rules", []),
            "exceptionPaths": raw_specification.get("exception_paths", []),
            "outputs": raw_specification.get("outputs", []),
            "successMetrics": raw_specification.get("success_metrics", []),
        }

        steps = []
        for index, item in enumerate(result.get("workflow_steps") or [], start=1):
            config = {"requiresApproval": bool(item.get("requires_approval"))}
            connector = (item.get("connector") or "").strip()
            if connector:
                config["connector"] = connector
            steps.append({
                "id": f"step-{index}",
                "type": item["type"],
                "name": item["name"],
                "description": item["description"],
                "config": config,
            })

        workflow = {
            "name": result.get("workflow_name") or "Optimized process workflow",
            "trigger": result.get("workflow_trigger") or "Start when the agreed trigger occurs.",
            "steps": steps,
        }
        self._ensure_approval_gate(
            workflow,
            force_approval=bool(result.get("human_approval_required")),
        )
        validate(workflow)

        benefits = []
        for item in result.get("expected_benefits") or []:
            benefit = {
                "metric": item.get("metric", ""),
                "description": item.get("description", ""),
                "baselineValue": item.get("baseline_value"),
                "targetValue": item.get("target_value"),
                "unit": item.get("unit", ""),
                "direction": item.get("direction", "not_applicable"),
                "confidence": item.get("confidence", "low"),
                "basis": item.get("basis", ""),
                "changePercent": None,
            }
            baseline = benefit["baselineValue"]
            target = benefit["targetValue"]
            direction = benefit["direction"]
            if baseline is not None and target is not None and float(baseline) != 0:
                if direction == "lower_is_better":
                    benefit["changePercent"] = round((float(baseline) - float(target)) / abs(float(baseline)) * 100, 1)
                elif direction == "higher_is_better":
                    benefit["changePercent"] = round((float(target) - float(baseline)) / abs(float(baseline)) * 100, 1)
            benefits.append(benefit)

        telemetry = getattr(self.ai_service, "last_call_telemetry", None) or {}
        analysis["optimization"] = {
            "status": "completed",
            "engine": "llm",
            "model": telemetry.get("model") or getattr(self.ai_service, "model", None),
            "summary": result.get("optimization_summary", ""),
            "designPrinciples": result.get("design_principles") or [],
            "recommendedChanges": [
                {
                    "title": item.get("title", ""),
                    "currentState": item.get("current_state", ""),
                    "proposedChange": item.get("proposed_change", ""),
                    "expectedEffect": item.get("expected_effect", ""),
                    "priority": item.get("priority", "medium"),
                }
                for item in (result.get("recommended_changes") or [])
            ],
            "expectedBenefits": benefits,
            "automationPotentialScore": max(0, min(100, int(result.get("automation_potential_score") or 0))),
            "automationPotentialReason": result.get("automation_potential_reason", ""),
        }
        analysis["automationOpportunities"] = result.get("automation_opportunities") or analysis.get("automationOpportunities", [])
        analysis["integrations"] = [
            {**item, "status": "planned_not_connected"}
            for item in (result.get("integrations") or analysis.get("integrations", []))
        ]
        analysis["risks"] = list(dict.fromkeys([*(analysis.get("risks") or []), *(result.get("risks") or [])]))
        analysis["assumptions"] = list(dict.fromkeys([*(analysis.get("assumptions") or []), *(result.get("assumptions") or [])]))
        analysis["humanApproval"] = {
            "required": bool(result.get("human_approval_required")) or any(
                step.get("type") in OUTBOUND_STEP_TYPES for step in workflow["steps"]
            ),
            "reason": result.get("human_approval_reason", ""),
            "gateBefore": next(
                (step.get("name", "") for step in workflow["steps"] if step.get("type") in OUTBOUND_STEP_TYPES),
                "",
            ),
        }
        analysis["proposedWorkflow"] = workflow

    @staticmethod
    def _llm_fallback_reason(error: Exception, language: str) -> str:
        error_name = type(error).__name__.lower()
        error_text = str(error).lower()

        if (
            "validationerror" in error_name
            or "lengthfinishreason" in error_name
            or "unexpected eof" in error_text
            or "while parsing" in error_text
        ):
            return (
                "Die KI-Antwort war unvollständig und konnte nicht eingelesen werden. "
                "Das Ausgabelimit wurde erhöht. Bitte die Analyse erneut starten."
                if language == "de"
                else "The AI response was incomplete and could not be parsed. "
                "The output limit has been increased. Please run the analysis again."
            )

        if any(term in error_text for term in ("insufficient_quota", "credit_balance_exhausted", "no credits remaining")):
            return (
                "OpenAI hat die Anfrage wegen fehlendem API-Guthaben abgelehnt. "
                "Bitte das Guthaben und das verwendete OpenAI-Projekt prüfen; Python-Fallback wurde verwendet."
                if language == "de"
                else "OpenAI rejected the request because API credit is exhausted. "
                "Check the credit balance and selected OpenAI project; Python fallback was used."
            )

        if any(term in error_text for term in ("invalid_api_key", "authenticationerror", "model_not_found", "does not exist")):
            return (
                "OpenAI-Zugang oder Modellkonfiguration ist ungültig. Bitte API-Schlüssel, Projektzugriff und Modellnamen in Render prüfen."
                if language == "de"
                else "OpenAI access or model configuration is invalid. Check the API key, project access and model name in Render."
            )

        return (
            "Die OpenAI-Anfrage ist fehlgeschlagen. Der deterministische Python-Fallback wurde verwendet. "
            "Details stehen in den Backend-Protokollen."
            if language == "de"
            else "The OpenAI request failed. The deterministic Python fallback was used. "
            "See backend logs for details."
        )

    def _apply_ai_result(
        self,
        analysis: dict,
        ai_result: dict,
        business_domain: str | None = None,
    ) -> None:
        raw_specification = ai_result.get("process_specification") or {}
        detected_domain = (raw_specification.get("business_domain") or "general").strip().lower()
        detected_domain = re.sub(r"[^a-z0-9]+", "_", detected_domain).strip("_")[:80] or "general"
        detected_label = (
            raw_specification.get("business_domain_label")
            or detected_domain.replace("_", " ").title()
        )

        # A selected gallery card is only a hint; free descriptions allow any domain.
        if business_domain and business_domain != "general":
            detected_domain = business_domain
            detected_label = analysis["detectedDetails"].get(
                "businessDomainLabel",
                business_domain.replace("_", " ").title(),
            )

        analysis["detectedDetails"]["businessDomain"] = detected_domain
        analysis["detectedDetails"]["businessDomainLabel"] = detected_label
        analysis["processSpecification"] = {
            "schemaVersion": "1.0",
            "businessDomain": detected_domain,
            "businessDomainLabel": detected_label,
            "goal": raw_specification.get("process_goal", ""),
            "actors": raw_specification.get("actors", []),
            "inputs": raw_specification.get("inputs", []),
            "systems": raw_specification.get("systems", []),
            "businessRules": raw_specification.get("business_rules", []),
            "exceptionPaths": raw_specification.get("exception_paths", []),
            "outputs": raw_specification.get("outputs", []),
            "successMetrics": raw_specification.get("success_metrics", []),
        }

        workflow_steps = []
        for index, item in enumerate(ai_result["workflow_steps"], start=1):
            config = {"requiresApproval": bool(item["requires_approval"])}
            connector = item.get("connector", "").strip()
            if connector:
                config["connector"] = connector
            workflow_steps.append({
                "id": f"step-{index}",
                "type": item["type"],
                "name": item["name"],
                "description": item["description"],
                "config": config,
            })

        workflow = {
            "name": ai_result["workflow_name"],
            "trigger": ai_result["workflow_trigger"],
            "steps": workflow_steps,
        }
        self._ensure_approval_gate(
            workflow,
            force_approval=bool(ai_result["human_approval_required"]),
        )
        validate(workflow)

        score = max(0, min(100, int(ai_result.get("automation_potential_score") or 0)))
        meaningful_steps = [
            step for step in workflow_steps
            if step["type"] not in {"trigger", "approval"}
        ]
        opportunities = ai_result.get("automation_opportunities") or []
        if score == 0 and (meaningful_steps or opportunities):
            score = min(85, max(20, 15 + len(meaningful_steps) * 8 + len(opportunities) * 5))

        analysis.update({
            "automationScore": score,
            "automationScoreNote": ai_result.get("automation_potential_reason", ""),
            "summary": ai_result["summary"],
            "currentProcess": ai_result["current_process"],
            "automationOpportunities": ai_result["automation_opportunities"],
            "integrations": [
                {**item, "status": "planned_not_connected"}
                for item in ai_result["integrations"]
            ],
            "humanApproval": {
                "required": bool(ai_result["human_approval_required"]) or any(
                    step["type"] in OUTBOUND_STEP_TYPES for step in workflow["steps"]
                ),
                "reason": ai_result["human_approval_reason"],
                "gateBefore": ai_result["human_approval_gate_before"],
            },
            "risks": ai_result["risks"],
            "assumptions": ai_result["assumptions"],
            "questions": ai_result["questions"],
            "proposedWorkflow": workflow,
        })

    @staticmethod
    def _ensure_approval_gate(workflow: dict, force_approval: bool = False) -> None:
        steps = workflow.setdefault("steps", [])
        if not steps or steps[0].get("type") != "trigger":
            steps.insert(0, {
                "type": "trigger",
                "name": "Start workflow",
                "description": workflow.get("trigger", "Start the workflow manually."),
                "config": {"requiresApproval": False},
            })

        if not any(step.get("type") == "generate" for step in steps):
            approval_index = next(
                (i for i, step in enumerate(steps) if step.get("type") == "approval"),
                len(steps),
            )
            steps.insert(approval_index, {
                "type": "generate",
                "name": "Prepare process output",
                "description": "Prepare the output defined by the process owner.",
                "config": {"requiresApproval": False},
            })

        outbound_positions = [
            i for i, step in enumerate(steps)
            if step.get("type") in OUTBOUND_STEP_TYPES
        ]
        must_approve = force_approval or bool(outbound_positions)
        if must_approve:
            first_outbound = outbound_positions[0] if outbound_positions else len(steps)
            prior_steps = steps[:first_outbound]
            last_preparation = max(
                (i for i, step in enumerate(prior_steps)
                 if step.get("type") in {"generate", "validate", "transform"}),
                default=first_outbound - 1,
            )
            steps[:] = [step for step in steps if step.get("type") != "approval"]
            first_outbound = next(
                (i for i, step in enumerate(steps) if step.get("type") in OUTBOUND_STEP_TYPES),
                len(steps),
            )
            insertion_index = min(last_preparation + 1, first_outbound)
            steps.insert(insertion_index, {
                "type": "approval",
                "name": "Human approval",
                "description": "Pause until an authorized person reviews and approves the output.",
                "config": {"requiresApproval": False},
            })

        for index, step in enumerate(steps, start=1):
            step["id"] = f"step-{index}"
            step.setdefault("config", {})
            if step.get("type") in OUTBOUND_STEP_TYPES:
                step["config"]["requiresApproval"] = True
